subroutine auto2e_BraKetTransfer_6_5_5_3(G, W, Ra, Rb, Rc, Rd)
!
! Transform (LS|KS), L=6..11, K=5..8 using the horizontal recurrence relation
! of Eq. 18 in Head-Gordon, M. and Pople, J.A. J. Chem. Phys. 89, 5777 (1988);
! doi: 10.1063/1.455553
!
! The output integrals are expressed in the Cartesian GTOs basis.
!
real(F64), dimension(210, *), intent(out) :: G
real(F64), dimension(308, 130), intent(in) :: W
real(F64), dimension(3), intent(in) :: Ra, Rb, Rc, Rd
real(F64), dimension(3) :: AB, CD
real(F64), dimension(308, 210) :: T
real(F64), dimension(210, 308) :: U
AB = Ra - Rb
CD = Rc - Rd
call auto2e_KetTransfer_5_3(T, W, CD(1), CD(2), CD(3))
U = transpose(T)
call auto2e_KetTransfer_6_5(G(:, 1:588), U, AB(1), AB(2), AB(3))
end subroutine auto2e_BraKetTransfer_6_5_5_3

